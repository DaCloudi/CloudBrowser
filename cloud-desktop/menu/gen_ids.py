#!/usr/bin/env python3
"""Read Desktop+'s headers and write the few IPC numbers Cloud Desktop's menu needs (dplus_ids.h).

Desktop+ takes settings changes as Windows messages whose number depends on the order of its
config enums, so they're worked out from the exact Desktop+ version being built.
Usage: python gen_ids.py <DesktopPlus/src/Shared> <out.h>
"""
import re
import sys
from pathlib import Path

shared = Path(sys.argv[1])


def enum_members(text, name):
    m = re.search(r"enum\s+" + name + r"\b[^{]*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit(f"gen_ids.py: enum {name} not found")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    out, value = {}, -1
    for item in body.split(","):
        item = item.strip()
        if not item or item.startswith("#"):
            continue
        if "=" in item:
            k, v = [x.strip() for x in item.split("=", 1)]
            value = int(v, 0)
        else:
            k = item
            value += 1
        out[k] = value
    return out


cfg = (shared / "ConfigManager.h").read_text(encoding="utf-8", errors="replace")
ipc = (shared / "InterprocessMessaging.h").read_text(encoding="utf-8", errors="replace")
b = enum_members(cfg, "ConfigID_Bool")
i = enum_members(cfg, "ConfigID_Int")
f = enum_members(cfg, "ConfigID_Float")
a = enum_members(ipc, "IPCActionID")
pa = enum_members(ipc, "IPCActionOverlayPosAdjustTarget")

ids = {
    "DP_ID_INT_CURRENT_OVERLAY": b["configid_bool_MAX"] + i["configid_int_interface_overlay_current_id"],
    "DP_ID_FLOAT_WIDTH": b["configid_bool_MAX"] + i["configid_int_MAX"] + f["configid_float_overlay_width"],
    "DP_ID_FLOAT_CURVATURE": b["configid_bool_MAX"] + i["configid_int_MAX"] + f["configid_float_overlay_curvature"],
    "DP_ACT_POSITION_ADJUST": a["ipcact_overlay_position_adjust"],
    "DP_ACT_ACTION_DO": a["ipcact_action_do"],
    "DP_ADJ_FORWBACK": pa["ipcactv_ovrl_pos_adjust_forwback"],
    "DP_ADJ_LOOKAT": pa["ipcactv_ovrl_pos_adjust_lookat"],
    "DP_ADJ_INCREASE": pa["ipcactv_ovrl_pos_adjust_increase"],
}
lines = ["// Generated by gen_ids.py from Desktop+ headers. Do not edit.", "#pragma once"]
lines += [f"#define {k} {v}" for k, v in ids.items()]
Path(sys.argv[2]).write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
