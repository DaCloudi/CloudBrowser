#!/usr/bin/env python3
"""Draw the Cloud Desktop in-headset menu (one picture per highlighted button) and its layout header."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).parent
W, H = 1000, 780
NAVY, PANEL, BTN, BTN_HOVER, LINE = (7, 16, 27, 245), (12, 22, 36, 255), (21, 33, 51, 255), (77, 141, 255, 255), (35, 48, 66, 255)
FONT = "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf"
title_font = ImageFont.truetype(FONT, 46)
btn_font = ImageFont.truetype(FONT, 38)
small_font = ImageFont.truetype("/usr/share/fonts/opentype/inter/Inter-Regular.otf", 26)

BUTTONS = [  # (code, label)
    ("RECENTER", "Recenter screens"), ("KEYBOARD", "Keyboard"),
    ("BIGGER", "Bigger"), ("SMALLER", "Smaller"),
    ("CLOSER", "Closer"), ("FURTHER", "Further"),
    ("CURVE_MORE", "More curve"), ("CURVE_LESS", "Flatter"),
    ("ROOM", "Room view on / off"), ("EXIT", "Leave desktop mode"),
]
M, TOP, GAP, ROWH = 40, 150, 14, 112
colw = (W - 2 * M - GAP) // 2
rects = []
for n in range(len(BUTTONS)):
    r, c = divmod(n, 2)
    x, y = M + c * (colw + GAP), TOP + r * (ROWH + GAP)
    rects.append((x, y, x + colw, y + ROWH))
CLOSE = (W - M - 70, 34, W - M, 104)


def draw(hover):
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((0, 0, W - 1, H - 1), 42, fill=NAVY, outline=LINE, width=3)
    # little cloud + title
    d.ellipse((M, 50, M + 34, 84), fill=(255, 255, 255, 255))
    d.ellipse((M + 18, 38, M + 62, 82), fill=(255, 255, 255, 255))
    d.rounded_rectangle((M, 62, M + 74, 84), 11, fill=(255, 255, 255, 255))
    d.text((M + 92, 42), "Cloud Desktop", font=title_font, fill=(255, 255, 255, 255))
    d.text((M + 2, 104), "Point and pull the trigger.  Press ☰ to close.", font=small_font, fill=(154, 167, 182, 255))
    for n, ((code, label), rc) in enumerate(zip(BUTTONS, rects)):
        on = hover == n
        fill = BTN_HOVER if on else (BTN if code != "EXIT" else (58, 24, 30, 255))
        d.rounded_rectangle(rc, 24, fill=fill)
        tw = d.textlength(label, font=btn_font)
        d.text(((rc[0] + rc[2] - tw) / 2, rc[1] + (ROWH - 46) / 2), label, font=btn_font, fill=(255, 255, 255, 255))
    on = hover == len(BUTTONS)
    d.rounded_rectangle(CLOSE, 20, fill=BTN_HOVER if on else BTN)
    cx, cy = (CLOSE[0] + CLOSE[2]) / 2, (CLOSE[1] + CLOSE[3]) / 2
    for s in (1, -1):
        d.line((cx - 16, cy - 16 * s, cx + 16, cy + 16 * s), fill=(255, 255, 255, 255), width=6)
    return img


draw(-1).save(OUT / "menu.png")
for n in range(len(BUTTONS) + 1):
    draw(n).save(OUT / f"menu_{n}.png")

lines = ["// Generated by make_menu.py. Do not edit.", "#pragma once",
         f"#define MENU_W {W}", f"#define MENU_H {H}", f"#define MENU_COUNT {len(BUTTONS) + 1}",
         "static const char* MENU_CODES[] = {" + ", ".join(f'"{c}"' for c, _ in BUTTONS) + ', "CLOSE"};',
         "static const int MENU_RECTS[][4] = {" + ", ".join("{%d, %d, %d, %d}" % r for r in rects + [CLOSE]) + "};"]
(OUT / "menu_layout.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("ok", len(rects) + 1)
