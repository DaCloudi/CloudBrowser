// API for the browser UI (tab strip + toolbar). Web pages never get this.
const { contextBridge, ipcRenderer } = require('electron');

// Chrome extension toolbar buttons (<browser-action-list>), normal windows only.
if (new URLSearchParams(location.search).get('incognito') !== '1') {
  try { require('electron-chrome-extensions/browser-action').injectBrowserAction(); }
  catch (e) { console.error('Extension buttons unavailable: ' + e.message); }
}

const send = (channel, ...args) => ipcRenderer.send('ui:' + channel, ...args);
const on = (channel, cb) => ipcRenderer.on(channel, (_e, data) => cb(data));

contextBridge.exposeInMainWorld('cloud', {
  newTab: () => send('new-tab'),
  closeTab: id => send('close-tab', id),
  switchTab: id => send('switch-tab', id),
  tabMenu: id => send('tab-menu', id),
  toggleMute: id => send('toggle-mute', id),
  navigate: (text, newTab) => send('navigate', text, !!newTab),
  search: (text, newTab) => send('search', text, !!newTab),
  back: () => send('back'),
  forward: () => send('forward'),
  reload: () => send('reload'),
  stop: () => send('stop'),
  home: () => send('home'),
  newIncognito: () => send('new-incognito'),
  makeDefault: () => send('make-default'),
  dismissDefault: () => send('dismiss-default'),
  installUpdate: () => send('install-update'),
  menu: () => send('menu'),
  toggleBookmark: () => send('toggle-bookmark'),
  openBookmark: (url, newTab) => send('open-bookmark', url, !!newTab),
  bookmarkMenu: id => send('bookmark-menu', id),
  openInternal: (name, hash) => send('open-internal', name, hash || ''),
  find: (text, opts) => send('find', text, opts || {}),
  findStop: () => send('find-stop'),
  setPageRect: r => send('page-rect', r),
  toggleVertical: () => send('toggle-vertical'),
  shieldMenu: () => send('shield-menu'),
  translateMenu: () => send('translate-menu'),
  sidebarApp: id => send('sidebar-app', String(id)),
  sidebarAppMenu: id => send('sidebar-app-menu', String(id)),
  sidebarAddMenu: () => send('sidebar-add-menu'),
  media: action => send('media', String(action)),
  onOpenExtension: cb => on('open-extension', cb),
  extensionList: () => ipcRenderer.invoke('ui:extensions'),
  pinExtension: id => send('pin-extension', id),
  manageExtensions: () => send('manage-extensions'),
  openWebStore: () => send('open-web-store'),
  reader: () => send('reader'),
  resetZoom: () => send('reset-zoom'),
  focusTab: id => send('focus-tab', id),
  moveTab: (id, index) => send('move-tab', id, index),
  addressMenu: hasSelection => send('address-menu', !!hasSelection),
  vpnToggle: () => send('vpn-toggle'),
  vpnCountry: c => send('vpn-country', c),
  vpnMode: m => send('vpn-mode', m),
  vpnImport: () => send('vpn-import'),
  vpnCheckIp: () => send('vpn-check-ip'),
  vpnNewIp: () => send('vpn-new-ip'),
  vpnIncognito: on => send('vpn-incognito', !!on),
  preconnect: text => send('preconnect', text),
  vpnInfo: () => ipcRenderer.invoke('ui:vpn'),
  onVpn: cb => on('vpn', cb),
  onBlurAddress: cb => on('blur-address', cb),
  storeInstall: id => send('store-install', id),
  storeRemove: id => send('store-remove', id),
  onStoreBusy: cb => on('store-busy', cb),
  toggleSidebar: () => send('toggle-sidebar'),
  windowControl: a => send('window-control', a),
  setOverlay: open => send('overlay', !!open),
  focusPage: () => send('focus-page'),
  suggest: q => ipcRenderer.invoke('ui:suggest', q),
  onState: cb => on('state', cb),
  onFocusAddress: cb => on('focus-address', cb),
  onFindOpen: cb => on('find-open', cb),
  onFindNext: cb => on('find-next', cb),
  onFindClose: cb => on('find-close', cb),
  onFindResult: cb => on('find-result', cb),
  onDownloadDone: cb => on('download-done', cb),
});
